// Regenerates assets/manifest.json from the files actually present in
// assets/models and assets/audio. Run it after adding or removing assets:
//   node tools/update-assets.js
// The game only requests files listed in the manifest (no 404 noise).
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const list = (dir, ext) =>
  existsSync(join(root, dir))
    ? readdirSync(join(root, dir)).filter((f) => f.toLowerCase().endsWith(ext)).sort()
    : [];

const manifest = {
  note: "Generated by tools/update-assets.js - lists the asset files that exist.",
  models: list("assets/models", ".glb"),
  audio: list("assets/audio", ".mp3"),
};
writeFileSync(join(root, "assets/manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`manifest: ${manifest.models.length} model(s), ${manifest.audio.length} audio file(s)`);
